// draw: 모든 도형에 pathLength=1 을 줘서 CSS(.icon-draw)로 stroke-dashoffset 애니메이션(선 그리기)을 쓸 수 있게 한다
function withPathLength(node) {
  const kids = node.type === Fragment ? node.props.children : node
  return Children.map(kids, (c) => (isValidElement(c) ? cloneElement(c, { pathLength: 1 }) : c))
}

export default function Icon({ name, className = 'h-6 w-6', strokeWidth = 2, draw = false }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={`${draw ? 'icon-draw ' : ''}${className}`}
    >
      {draw ? withPathLength(PATHS[name]) : PATHS[name]}
    </svg>
  )
}
